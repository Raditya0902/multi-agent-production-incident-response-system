"""
Read the latest synthetic regression results and print a Markdown summary table.

Usage:
    python scripts/export_benchmark_report.py
    python scripts/export_benchmark_report.py --output docs/benchmark-results.generated.md
"""
import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

RESULTS_DIR = Path(__file__).parent.parent / "tests" / "benchmark" / "results"


def _load_results() -> dict:
    results = RESULTS_DIR / "synthetic-latest.json"
    if not results.exists():
        results = RESULTS_DIR / "latest.json"
    if not results.exists():
        print(f"Error: no result found in {RESULTS_DIR}. Run the benchmark first:", file=sys.stderr)
        print("  python -m tests.benchmark.run_benchmark", file=sys.stderr)
        sys.exit(1)
    with results.open() as f:
        return json.load(f)


def _severity_badge(severity: str) -> str:
    return {"P0": "🔴 P0", "P1": "🟠 P1", "P2": "🟡 P2"}.get(severity, severity)


def _build_synthetic_report(data: dict) -> str:
    metrics = data["metrics"]
    matrix = metrics["disagreement_matrix"]
    lines = [
        "# Synthetic regression suite",
        "",
        f"Run {data['run_at']} · auto-approve",
        "",
        f"Resolved **{metrics['resolved_count']}/{metrics['total_cases']}** with service and held-out pytest.",
        f"Invalid / unscored **{metrics['invalid_count']}**.",
        "",
        "| Both | Tests only | Pattern only | Neither | Unscored |",
        "|---|---|---|---|---|",
        f"| {matrix['both']} | {matrix['tests_only']} | {matrix['pattern_only']} | "
        f"{matrix['neither']} | {metrics['matrix_unscored_count']} |",
        "",
        "| Scenario | Status | Real tests exercised | Pattern match | Retries | Time |",
        "|---|---|---|---|---|---|",
    ]
    for scenario in data["scenarios"]:
        pattern = {None: "—", True: "yes", False: "no"}[scenario["pattern_match"]]
        used = "yes" if scenario["used_real_tests"] else "no"
        lines.append(
            f"| {scenario['name']} | {scenario['status']} | {used} | {pattern} | "
            f"{scenario['retries']} | {scenario['elapsed']:.2f}s |"
        )
    return "\n".join(lines)


def _build_report(data: dict) -> str:
    if data.get("schema_version") == 2:
        return _build_synthetic_report(data)
    run_at = data.get("run_at", "unknown")
    metrics = data.get("metrics", {})
    scenarios = data.get("scenarios", [])

    try:
        dt = datetime.fromisoformat(run_at).astimezone(timezone.utc)
        run_date = dt.strftime("%Y-%m-%d %H:%M UTC")
    except (ValueError, TypeError):
        run_date = run_at

    lines = [
        "# Historical benchmark report (legacy scoring)",
        "",
        f"**Generated:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}  ",
        f"**Benchmark run:** {run_date}",
        "",
        "---",
        "",
        "## Aggregate Metrics",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Patch correctness | **{metrics.get('patch_correctness_pct', 0):.1f}%** |",
        f"| First-attempt success rate | **{metrics.get('first_attempt_success_rate', 0):.1f}%** |",
        f"| Retry success rate | **{metrics.get('retry_success_rate', 0):.1f}%** |",
        f"| False positive rate | **{metrics.get('false_positive_rate', 0):.1f}%** |",
        f"| Average runtime | **{metrics.get('avg_run_time_seconds', 0):.1f}s** per scenario |",
        f"| Escalation rate | **{metrics.get('escalation_rate', 0):.1f}%** |",
        f"| Total scenarios | **{metrics.get('total_cases', len(scenarios))}** |",
        "",
        "---",
        "",
        "## Per-Scenario Results",
        "",
        "| # | Scenario | File | Severity | Pass | Correct | Retries | Time |",
        "|---|---|---|---|---|---|---|---|",
    ]

    for s in scenarios:
        passed = "✓" if s.get("tests_passed") else "✗"
        correct = "✓" if s.get("patch_correct") else "✗"
        escalated = " 🆘" if s.get("escalated") else ""
        lines.append(
            f"| {s['id']} "
            f"| {s['name']} "
            f"| `{s['target_file']}` "
            f"| {_severity_badge(s.get('severity', '?'))} "
            f"| {passed}{escalated} "
            f"| {correct} "
            f"| {s.get('retry_count', '?')} "
            f"| {s.get('elapsed', 0):.1f}s |"
        )

    lines += [
        "",
        "**Pass** — tests passed in sandbox.  ",
        "**Correct** — patch matched ground-truth fix pattern.  ",
        "**Retries** — total fix attempts (1 = passed on first try).",
        "",
        "---",
        "",
        "_Generated by `scripts/export_benchmark_report.py`_",
    ]

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Export benchmark results as Markdown.")
    parser.add_argument(
        "--output",
        metavar="PATH",
        help="Write Markdown to this file instead of stdout",
    )
    args = parser.parse_args()

    data = _load_results()
    report = _build_report(data)

    if args.output:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(report)
        print(f"Report written to {out_path}")
    else:
        print(report)


if __name__ == "__main__":
    main()
