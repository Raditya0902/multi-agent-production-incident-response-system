"""
Read tests/benchmark/results/latest.json and print a Markdown summary table.

Usage:
    python scripts/export_benchmark_report.py
    python scripts/export_benchmark_report.py --output docs/benchmark-results.generated.md
"""
import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

RESULTS_PATH = Path(__file__).parent.parent / "tests" / "benchmark" / "results" / "latest.json"


def _load_results() -> dict:
    if not RESULTS_PATH.exists():
        print(f"Error: {RESULTS_PATH} not found. Run the benchmark first:", file=sys.stderr)
        print("  python -m tests.benchmark.run_benchmark", file=sys.stderr)
        sys.exit(1)
    with RESULTS_PATH.open() as f:
        return json.load(f)


def _severity_badge(severity: str) -> str:
    return {"P0": "🔴 P0", "P1": "🟠 P1", "P2": "🟡 P2"}.get(severity, severity)


def _build_report(data: dict) -> str:
    run_at = data.get("run_at", "unknown")
    metrics = data.get("metrics", {})
    scenarios = data.get("scenarios", [])

    try:
        dt = datetime.fromisoformat(run_at).astimezone(timezone.utc)
        run_date = dt.strftime("%Y-%m-%d %H:%M UTC")
    except (ValueError, TypeError):
        run_date = run_at

    lines = [
        "# Benchmark Report",
        "",
        f"**Generated:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}  ",
        f"**Benchmark run:** {run_date}",
        "",
        "---",
        "",
        "## Aggregate Metrics",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Patch correctness | **{metrics.get('patch_correctness_pct', 0):.1f}%** |",
        f"| First-attempt success rate | **{metrics.get('first_attempt_success_rate', 0):.1f}%** |",
        f"| Retry success rate | **{metrics.get('retry_success_rate', 0):.1f}%** |",
        f"| False positive rate | **{metrics.get('false_positive_rate', 0):.1f}%** |",
        f"| Average runtime | **{metrics.get('avg_run_time_seconds', 0):.1f}s** per scenario |",
        f"| Escalation rate | **{metrics.get('escalation_rate', 0):.1f}%** |",
        f"| Total scenarios | **{metrics.get('total_cases', len(scenarios))}** |",
        "",
        "---",
        "",
        "## Per-Scenario Results",
        "",
        "| # | Scenario | File | Severity | Pass | Correct | Retries | Time |",
        "|---|---|---|---|---|---|---|---|",
    ]

    for s in scenarios:
        passed = "✓" if s.get("tests_passed") else "✗"
        correct = "✓" if s.get("patch_correct") else "✗"
        escalated = " 🆘" if s.get("escalated") else ""
        lines.append(
            f"| {s['id']} "
            f"| {s['name']} "
            f"| `{s['target_file']}` "
            f"| {_severity_badge(s.get('severity', '?'))} "
            f"| {passed}{escalated} "
            f"| {correct} "
            f"| {s.get('retry_count', '?')} "
            f"| {s.get('elapsed', 0):.1f}s |"
        )

    lines += [
        "",
        "**Pass** — tests passed in sandbox.  ",
        "**Correct** — patch matched ground-truth fix pattern.  ",
        "**Retries** — total fix attempts (1 = passed on first try).",
        "",
        "---",
        "",
        "_Generated by `scripts/export_benchmark_report.py`_",
    ]

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Export benchmark results as Markdown.")
    parser.add_argument(
        "--output",
        metavar="PATH",
        help="Write Markdown to this file instead of stdout",
    )
    args = parser.parse_args()

    data = _load_results()
    report = _build_report(data)

    if args.output:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(report)
        print(f"Report written to {out_path}")
    else:
        print(report)


if __name__ == "__main__":
    main()
